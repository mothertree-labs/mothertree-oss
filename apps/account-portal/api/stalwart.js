/**
 * Stalwart Mail Server API client (Stalwart v1 JMAP management API)
 *
 * Every operation is a `POST <STALWART_API_URL>/jmap/` with HTTP Basic auth as
 * the recovery admin, using the `urn:stalwart:jmap` management methods
 * (`x:Account/*`, `x:Domain/*`, `x:AppPassword/*`, `x:Action/*`).
 *
 * v1 differences from the 0.15 REST API this replaced (issue #715):
 *  - Accounts are named by their LOCAL part plus a domainId; the email address
 *    is derived (`emailAddress`). Callers still pass full email addresses.
 *  - Errors come back as HTTP 200: a method-level `["error", {type}]` response
 *    or per-id `notCreated` / `notUpdated` / `notDestroyed` entries.
 *  - App password secrets are generated by the server and returned once.
 */

const STALWART_API_URL = process.env.STALWART_API_URL;
const STALWART_ADMIN_PASSWORD = process.env.STALWART_ADMIN_PASSWORD;

const JMAP_USING = ['urn:ietf:params:jmap:core', 'urn:stalwart:jmap'];

function getAdminAuth() {
  if (!STALWART_API_URL || !STALWART_ADMIN_PASSWORD) {
    throw new Error('Stalwart API not configured (STALWART_API_URL or STALWART_ADMIN_PASSWORD missing)');
  }
  return 'Basic ' + Buffer.from(`admin:${STALWART_ADMIN_PASSWORD}`).toString('base64');
}

/**
 * Send one JMAP request and return its method responses keyed by call id.
 * Throws on a non-2xx HTTP status (e.g. 401 bad credentials) and on any
 * method-level `["error", {...}, callId]` response.
 */
async function jmap(methodCalls) {
  const adminAuth = getAdminAuth();
  const response = await fetch(`${STALWART_API_URL}/jmap/`, {
    method: 'POST',
    headers: {
      'Authorization': adminAuth,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({ using: JMAP_USING, methodCalls }),
  });

  if (!response.ok) {
    const text = await response.text().catch(() => '');
    throw new Error(`Stalwart JMAP request failed: ${response.status} ${text}`.trim());
  }

  const data = await response.json();
  const results = {};
  for (const [name, args, callId] of data.methodResponses || []) {
    if (name === 'error') {
      const call = methodCalls.find((c) => c[2] === callId);
      const method = call ? call[0] : callId;
      throw new Error(`Stalwart ${method} failed: ${args?.type || 'unknown'}${args?.description ? ` - ${args.description}` : ''}`);
    }
    results[callId] = args;
  }
  for (const [method, , callId] of methodCalls) {
    if (!results[callId]) {
      throw new Error(`Stalwart ${method} failed: no response for call "${callId}"`);
    }
  }
  return results;
}

function describeSetError(err) {
  if (!err) return 'unknown';
  const props = Array.isArray(err.properties) && err.properties.length ? ` [${err.properties.join(', ')}]` : '';
  return `${err.type || 'unknown'}${err.description ? ` - ${err.description}` : ''}${props}`;
}

/** Throw if a /set response reports a failure for any create/update/destroy. */
function assertSetOk(label, result) {
  for (const key of ['notCreated', 'notUpdated', 'notDestroyed']) {
    const failures = result?.[key];
    if (failures && Object.keys(failures).length > 0) {
      const [id, err] = Object.entries(failures)[0];
      throw new Error(`${label} failed (${id}): ${describeSetError(err)}`);
    }
  }
}

/** Split and normalise an email address into { local, domain }. */
function splitEmail(email) {
  const addr = String(email || '').trim().toLowerCase();
  const at = addr.lastIndexOf('@');
  if (at <= 0 || at === addr.length - 1) {
    throw new Error(`Invalid email address: "${email}"`);
  }
  return { local: addr.slice(0, at), domain: addr.slice(at + 1), address: addr };
}

// Domain name -> Stalwart domainId. Domains are created by deploy-stalwart.sh
// and never renamed, so positive lookups are cached for the process lifetime.
const domainIdCache = new Map();

async function getDomainId(domain) {
  if (domainIdCache.has(domain)) return domainIdCache.get(domain);
  const res = await jmap([['x:Domain/query', { filter: { name: domain } }, 'd']]);
  const id = res.d.ids?.[0];
  if (!id) {
    throw new Error(`Stalwart domain "${domain}" not configured`);
  }
  domainIdCache.set(domain, id);
  return id;
}

/**
 * Look up an account by email address. Returns the account object (with `id`)
 * or null. A single request: query by local part, then get the matches via a
 * back-reference and pick the one whose primary address is `email`.
 */
async function findAccount(email) {
  const { local, address } = splitEmail(email);
  const res = await jmap([
    ['x:Account/query', { filter: { name: local } }, 'q'],
    ['x:Account/get', {
      '#ids': { resultOf: 'q', name: 'x:Account/query', path: '/ids' },
      properties: ['name', 'emailAddress'],
    }, 'g'],
  ]);
  const list = res.g.list || [];
  return list.find((a) => (a.emailAddress || '').toLowerCase() === address) || null;
}

async function requireAccount(email) {
  const account = await findAccount(email);
  if (!account) {
    throw new Error(`Stalwart account for ${email} not found`);
  }
  return account;
}

/**
 * Reload Stalwart settings (`ReloadSettings` action) so RCPT TO reflects a
 * just-created account. Non-fatal: a reload failure is logged, not thrown.
 */
async function reloadConfig() {
  try {
    const res = await jmap([['x:Action/set', { create: { r: { '@type': 'ReloadSettings' } } }, 'r']]);
    assertSetOk('Stalwart config reload', res.r);
  } catch (err) {
    console.warn(`Stalwart: config reload failed (non-fatal): ${err.message}`);
  }
}

/**
 * Ensure a user account exists in Stalwart for `email`.
 * Returns { created: true } when this call created it, { created: false } when
 * it already existed (including losing a concurrent-create race).
 */
async function ensureUserExists(email, name, quotaBytes) {
  const { local, domain } = splitEmail(email);

  if (await findAccount(email)) {
    return { created: false };
  }

  console.log(`Stalwart: creating account for ${email}`);
  const domainId = await getDomainId(domain);
  const account = {
    '@type': 'User',
    name: local,
    domainId,
    description: name || '',
  };
  if (quotaBytes) {
    account.quotas = { maxDiskQuota: quotaBytes };
  }

  const res = await jmap([['x:Account/set', { create: { n: account } }, 'c']]);
  const notCreated = res.c.notCreated?.n;
  if (notCreated) {
    // Duplicate (e.g. a concurrent create) — same as the old 409 / fieldAlreadyExists.
    if (notCreated.type === 'primaryKeyViolation') {
      return { created: false };
    }
    throw new Error(`Stalwart account creation failed for ${email}: ${describeSetError(notCreated)}`);
  }
  if (!res.c.created?.n?.id) {
    throw new Error(`Stalwart account creation for ${email} returned no id`);
  }

  // Clear directory cache so RCPT TO picks up the new account immediately
  await reloadConfig();

  console.log(`Stalwart: account ${email} created`);
  return { created: true };
}

/**
 * List app passwords for a user. Returns [{ name }] where name is the
 * description given at creation. Returns [] when the account does not exist.
 */
async function listAppPasswords(email) {
  const account = await findAccount(email);
  if (!account) return [];
  const res = await jmap([['x:AppPassword/get', { accountId: account.id }, 'a']]);
  return (res.a.list || []).map((p) => ({ name: p.description || '' }));
}

/**
 * Create an app password named `deviceName` for a user.
 * The secret is generated by Stalwart and returned ONCE as `password`.
 */
async function createAppPassword(email, deviceName) {
  const account = await requireAccount(email);
  const res = await jmap([['x:AppPassword/set', {
    accountId: account.id,
    create: { a: { description: deviceName } },
  }, 'p']]);
  assertSetOk(`Stalwart app password creation for ${email}`, res.p);
  const secret = res.p.created?.a?.secret;
  if (!secret) {
    throw new Error(`Stalwart app password creation for ${email} returned no secret`);
  }
  return { success: true, password: secret };
}

/**
 * Revoke an app password by name (its description). If several share the
 * name, all of them are revoked — the UI cannot tell them apart.
 */
async function revokeAppPassword(email, passwordName) {
  const account = await requireAccount(email);
  const list = await jmap([['x:AppPassword/get', { accountId: account.id }, 'a']]);
  const ids = (list.a.list || []).filter((p) => p.description === passwordName).map((p) => p.id);
  if (ids.length === 0) {
    throw new Error(`App password "${passwordName}" not found`);
  }
  const res = await jmap([['x:AppPassword/set', { accountId: account.id, destroy: ids }, 'r']]);
  assertSetOk(`Stalwart app password revoke for ${email}`, res.r);
  return { success: true };
}

module.exports = {
  ensureUserExists,
  listAppPasswords,
  createAppPassword,
  revokeAppPassword,
};
